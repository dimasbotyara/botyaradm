# Собираем последнее показанное приветствие, чтобы не повторяться
_last_greeting: str | None = None


def _get_period() -> str:
    """Определяем период суток по текущему часу."""
    hour = datetime.now().hour

    if 0 <= hour < 5:
        return "night"
    elif 5 <= hour < 7:
        return "early_morning"
    elif 7 <= hour < 12:
        return "morning"
    elif 12 <= hour < 17:
        return "day"
    elif 17 <= hour < 21:
        return "evening"
    else:
        return "late_evening"


def get_greeting(name: str) -> str:
    """
    Возвращает случайное приветствие для текущего времени суток.
    Гарантирует, что подряд не будет одно и то же.
    """
    global _last_greeting

    period = _get_period()
    pool = _GREETINGS[period]

    # Если пул больше 1, исключаем последнее показанное
    if len(pool) > 1 and _last_greeting in pool:
        candidates = [g for g in pool if g != _last_greeting]
    else:
        candidates = pool

    greeting = random.choice(candidates)
    _last_greeting = greeting

    return greeting.format(name=name)
